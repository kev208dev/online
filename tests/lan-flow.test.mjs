import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { createLanService } from '../server/service.mjs';
import { createLanClient, pairLan } from '../src/state/lanClient.ts';
import { mergeLanSnapshot, performLanAction } from '../src/state/sharedMode.ts';
import { createAppState } from '../src/state/queueRepository.ts';

test('two independent phones share queue/coupon changes while branch selection stays local', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'online-flow-'));
  const service = createLanService({ dataPath: join(dir, 'state.json'), host: '127.0.0.1', port: 0 });
  const { port, codes } = await service.listen();
  t.after(async () => { await service.close(); await rm(dir, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${port}`;
  const customerPair = await pairLan(base, codes.customer);
  const merchantPair = await pairLan(base, codes.merchant);
  const customer = createLanClient(base, customerPair.token);
  const merchant = createLanClient(base, merchantPair.token);
  const local = createAppState();
  local.queue.selectedBranchId = 'dcc';
  let customerView = mergeLanSnapshot(local, customerPair.state);
  let merchantView = mergeLanSnapshot(createAppState(), merchantPair.state);
  const updateCustomer = (remote) => { customerView = mergeLanSnapshot(local, remote); };
  const updateMerchant = (remote) => { merchantView = mergeLanSnapshot(createAppState(), remote); };
  await performLanAction(merchant, true, { type: 'setCount', branchId: 'main', count: 2 }, updateMerchant);
  await performLanAction(customer, true, { type: 'join', branchId: 'main', acceptedTerms: true }, updateCustomer);
  assert.equal(customerView.queue.selectedBranchId, 'dcc');
  assert.equal(customerView.queue.wait.branchId, 'main');
  assert.equal(customerView.queue.wait.peopleAhead, 2);
  assert.equal(merchantView.queue.wait, null);
  const coupon = await performLanAction(customer, true, { type: 'issueCoupon', storeId: 'madeby' }, updateCustomer);
  assert.match(coupon.result.couponCode, /^ONLINE-COUPON-/);
  await performLanAction(merchant, true, { type: 'redeemCoupon', storeId: 'madeby', code: coupon.result.couponCode }, updateMerchant);
  customerView = mergeLanSnapshot(local, (await customer.read()).state);
  assert.ok(customerView.commerce.coupons[0].usedAt);
  await performLanAction(merchant, true, { type: 'advance', branchId: 'main' }, updateMerchant);
  await performLanAction(merchant, true, { type: 'advance', branchId: 'main' }, updateMerchant);
  customerView = mergeLanSnapshot(local, (await customer.read()).state);
  assert.equal(customerView.queue.wait.peopleAhead, 0);
  await performLanAction(merchant, true, { type: 'verifyEntry', branchId: 'main', code: customerView.queue.wait.entryCode }, updateMerchant);
  customerView = mergeLanSnapshot(local, (await customer.read()).state);
  assert.equal(customerView.queue.wait.status, 'completed');
});

test('offline or rejected shared writes never commit a local snapshot or silently retry', async () => {
  const local = createAppState();
  let commits = 0;
  let calls = 0;
  const client = { act: async () => { calls++; throw new Error('offline'); } };
  const action = { type: 'join', branchId: 'main', acceptedTerms: true };
  const blocked = await performLanAction(client, false, action, () => commits++);
  assert.match(blocked.reason, /연결 끊김/);
  assert.equal(calls, 0);
  const failed = await performLanAction(client, true, action, () => commits++);
  assert.ok(failed.reason);
  assert.equal(calls, 1);
  assert.equal(commits, 0);
  assert.equal(local.queue.wait, null);
});
